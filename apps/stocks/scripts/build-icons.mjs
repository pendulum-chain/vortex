// Generates src/components/icons.js: only the Phosphor icons fatia. imports from it, in the three
// weights the UI uses (regular, bold, fill). The full @phosphor-icons/react components carry six
// weights each (~2.4 KB per icon) and would sit in the entry chunk. Run after adding an icon:
//   node apps/stocks/scripts/build-icons.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const APP = fileURLToPath(new URL("../", import.meta.url));
const SRC = join(APP, "src");
const OUT = join(SRC, "components/icons.js");
const WEIGHTS = ["regular", "bold", "fill"];

const walk = (dir) => readdirSync(dir).flatMap((name) => {
  const path = join(dir, name);
  return statSync(path).isDirectory() ? walk(path) : [path];
});

const names = new Set();
for (const file of walk(SRC).filter((path) => /\.(jsx?|mjs)$/.test(path) && path !== OUT)) {
  for (const [, list] of readFileSync(file, "utf8").matchAll(/import\s*\{([^}]+)\}\s*from\s*["'][./]*(?:components\/)?icons\.js["']/g)) {
    for (const name of list.split(",").map((item) => item.trim()).filter(Boolean)) names.add(name);
  }
}

const require = createRequire(join(APP, "package.json"));
const pkgDir = join(require.resolve("@phosphor-icons/react"), "../..");
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;

function toNodes(element) {
  const children = element?.props?.children;
  const list = Array.isArray(children) ? children : children ? [children] : [];
  return list.flatMap((child) => (typeof child?.type === "string" ? [[child.type, Object.fromEntries(Object.entries(child.props).filter(([key]) => key !== "children"))]] : toNodes(child)));
}

const entries = [];
for (const name of [...names].sort()) {
  const defs = (await import(pathToFileURL(join(pkgDir, "dist/defs", `${name}.es.js`)).href)).default;
  const weights = Object.fromEntries(WEIGHTS.map((weight) => [weight, toNodes(defs.get(weight))]));
  entries.push(`export const ${name} = icon(${JSON.stringify(weights)});`);
}

writeFileSync(OUT, `// GENERATED by scripts/build-icons.mjs from @phosphor-icons/react ${version} (MIT, phosphoricons.com).
// Only the icons fatia. uses, in the weights regular/bold/fill. Do not edit: re-run the script.
import { createElement } from "react";

function icon(weights) {
  return function Icon({ size = 24, weight = "regular", color = "currentColor", ...props }) {
    const nodes = weights[weight] ?? weights.regular;
    return createElement("svg", { xmlns: "http://www.w3.org/2000/svg", width: size, height: size, viewBox: "0 0 256 256", fill: color, focusable: "false", ...props },
      ...nodes.map(([tag, attributes], index) => createElement(tag, { key: index, ...attributes })));
  };
}

${entries.join("\n")}
`);
console.log(`${relative(APP, OUT)}: ${names.size} icons from @phosphor-icons/react ${version}`);
